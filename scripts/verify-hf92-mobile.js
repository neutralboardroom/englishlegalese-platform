#!/usr/bin/env node
'use strict';
const assert=require('node:assert/strict'),fs=require('node:fs'),path=require('node:path');
const root=path.join(__dirname,'..');const read=p=>fs.readFileSync(path.join(root,p),'utf8');
const hub=read('learn/app/index.html'),native=read('mobile/native/www/index.html');
const manifest=JSON.parse(read('manifest.webmanifest'));
const cap=JSON.parse(read('mobile/native/capacitor.config.json'));
const pkg=JSON.parse(read('mobile/native/package.json'));
const spec=read('tests/v1850-packages.spec.js');
let n=0;const ok=(cond,message)=>{assert.ok(cond,message);n++};
for(const p of ['/learn/legal-english/','/learn/business-english/','/learn/courses/','/learn/free-writing-exercise/','/learn/reading-precision/','/learn/enroll/','/learn/account/','/learn/install/'])ok(hub.includes('href="'+p+'"'),'Hub direct route '+p);
for(const id of ['learn','practice','classes','account'])ok(hub.includes('id="'+id+'"')&&hub.includes('href="#'+id+'"'),'Mobile navigation '+id);
for(const security of ['localStorage','sessionStorage','indexedDB','fetch(','XMLHttpRequest','document.cookie'])ok(!hub.includes(security),'No mobile landing storage/data transfer '+security);
ok(hub.includes('viewport-fit=cover')&&hub.includes('env(safe-area-inset-bottom)'),'phone safe area');
ok(hub.includes('focus-visible')&&hub.includes('Skip to learning options'),'keyboard navigation');
ok(hub.includes('prefers-reduced-motion'),'reduced motion preference');
ok(hub.includes('Native iOS and Android applications are in development'),'truthful native status');
ok(read('index.html').includes('href="/learn/app/"'),'homepage links to mobile hub');
ok(read('learn/install/index.html').includes('href="/learn/app/"'),'install guide links to mobile hub');
ok(read('sw.js').includes("'/learn/app/'"),'public offline fallback');
ok(read('sw.js').includes('PUBLIC_FALLBACK_PATHS'),'no private caching');
ok(manifest.start_url==='/'&&manifest.display==='standalone','preserve original app launcher / and mode');
ok(manifest.shortcuts.length===3,'preserve 3 protected app shortcuts');
ok(cap.appId==='com.englishlegalese.prototype'&&cap.webDir==='www','development-only native ID');
ok(!('url' in (cap.server||{})),'no remote WebView server URL');
ok(pkg.private===true,'prototype package never published to npm');
ok(/https:\/\/englishlegalese\.com\/learn\/app\//.test(native),'native shell links to canonical domain');
ok(native.includes('target="_blank"')&&native.includes('rel="noopener noreferrer"'),'external browser intent');
for(const security of ['localStorage','sessionStorage','indexedDB','fetch(','XMLHttpRequest','password','access_token','client_secret'])ok(!native.includes(security),'no native private-data storage '+security);
ok(spec.includes("locator('p.v1850-boundary').filter({hasText:'Indicative multi-seat discount'})"),'HF91 stable semantic discount locator');
ok(spec.includes("toContainText('15%')"),'15% employer policy assertion retained');
ok(spec.includes("expect(sent).not.toHaveProperty('employee_seats')")&&spec.includes("expect(sent).not.toHaveProperty('organization')"),'employer PII privacy assertions retained');
console.log('HF92 source/mobile safeguards PASS: '+n);
