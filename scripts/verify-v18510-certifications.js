'use strict';
const assert=require('node:assert/strict'),fs=require('node:fs');
const read=p=>fs.readFileSync(p,'utf8'),pkg=require('../package.json');
const home=read('index.html'),app=read('app.js');
const directory=read('learn/certifications/index.html');
const levels=['A1','A2','B1','B2','C1','C2'];
assert.equal(pkg.version,'1.85.10');
for(const [track,topic]of [['legal','Legal'],['business','Business']]){
 const path='learn/'+track+'-english-certification/index.html';
 const page=read(path);
 assert(page.includes('name="englishlegalese-release" content="1.85.10"'));
 assert(page.includes('rel="canonical" href="https://englishlegalese.com/learn/'+track+'-english-certification/"'));
 assert(page.includes('EnglishLegalese '+topic+' English Certification'));
 assert(page.includes('It has its own assessments, results and certificate records'));
 assert(page.includes('CEFR-informed')&&page.includes('Council of Europe'));
 assert(page.includes('live human-proctored'));
 assert(page.includes('EnglishLegalese will issue a uniquely numbered'));
 assert(page.includes('do not transfer or automatically establish a level'));
 assert(page.includes('href="/hf24-certifications.css?v=1.85.10"'));
 for(const level of levels)assert(page.includes('<th scope="row">'+level+'</th>'),track+' level missing: '+level);
 assert(read('learn/'+track+'-english/index.html').includes('/learn/'+track+'-english-certification/'));
}
assert(directory.includes('will offer and issue its own original'));
assert(directory.includes('/learn/legal-english-certification/'));
assert(directory.includes('/learn/business-english-certification/'));
assert(directory.includes('has not established external accreditation'));
assert(read('hf24-certifications.css').includes('.v1940-cert-grid'));
assert(home.includes('<a href="/learn/certifications/">Certifications</a>'));
assert(app.includes('current and prospective employers gauge professional communication skills'));
console.log('PASS HF24: two EnglishLegalese branded tracks with independent six-level exams, teacher supervision and employer clarity; common CEFR reference not false accreditation.');
