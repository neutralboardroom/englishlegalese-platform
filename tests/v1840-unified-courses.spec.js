const {test,expect}=require('@playwright/test');
test('v1.84 homepage Courses is one unified 28 class-topic catalog without a second nine-course listing',async({page})=>{
 await page.goto('/#courses');await page.locator('body.v1590-ready').waitFor();
 const course=page.locator('#courses'),catalog=course.locator('#v1800-class-catalog');
 await expect(course.locator('.section-head h2')).toContainText('28 class topics');
 await expect(catalog.locator('.v1800-class-count')).toContainText('28 class topics');
 await expect(catalog.locator('.v1800-class-card')).toHaveCount(12);
 await expect(catalog.locator('.v1800-catalog-intro')).not.toContainText('expanded');
 await expect(catalog.locator('.v1800-catalog-intro')).not.toContainText('additional');
 await expect(course.locator('#v1840-sample-lessons')).not.toHaveAttribute('open');
 await expect(course.locator('#v1840-sample-lessons')).toContainText('practice activities, not separate class topics');
 await expect(course.locator('.v1580-course-card')).toHaveCount(9);
 await expect(course.locator('.v1580-course-card:visible')).toHaveCount(0);
 await catalog.getByRole('button',{name:'Show all 28 class topics'}).click();
 await expect(catalog.locator('.v1800-class-card')).toHaveCount(28);
 await expect(catalog.locator('h3')).toHaveCount(28);
 await expect(page.locator('#live-classes #v1800-class-catalog')).toHaveCount(0);
});
test('v1.84 dedicated Courses page displays 28 complete selectable class topics, not only nine',async({page})=>{
 await page.goto('/learn/courses/');
 const catalog=page.locator('#v1840-course-mount #v1800-class-catalog');
 await expect(page.getByRole('heading',{name:'Legal English Courses',exact:true})).toBeVisible();
 await expect(page.locator('.v1840-lead')).toContainText('all 28');
 await expect(catalog.locator('.v1800-class-card')).toHaveCount(28);
 await expect(catalog.locator('.v1800-class-count')).toContainText('28 class topics');
 await catalog.locator('#v1800-class-track').selectOption('Legal specialties');
 await expect(catalog.locator('.v1800-class-card')).toHaveCount(12);
 await catalog.locator('#v1800-class-track').selectOption('all');
 await catalog.locator('#v1800-class-search').fill('cybersecurity');
 await expect(catalog.locator('.v1800-class-card')).toHaveCount(1);
 await catalog.locator('#v1800-class-search').fill('');
 await expect(catalog.locator('.v1800-class-card')).toHaveCount(28);
 await catalog.locator('.v1800-class-card').first().getByRole('button',{name:'View lesson & teacher materials'}).click();
 const preview=catalog.locator('#v1800-class-viewer');
 await expect(preview).toBeVisible();
 await expect(preview.locator('.v1800-material-block').first().locator('ol > li')).toHaveCount(4);
 await expect(preview.locator('.v1800-glossary dt')).toHaveCount(5);
 await expect(preview.locator('.v1800-quiz-question')).toHaveCount(3);
 await expect(preview).toContainText('At-home practice and self-check');
 await expect(preview.locator('.v1800-teacher')).toHaveCount(1);
 await expect(preview).toContainText('NOT BOOKABLE');
 const dims=await page.evaluate(()=>({scroll:document.documentElement.scrollWidth,width:innerWidth}));
 expect(dims.scroll).toBeLessThanOrEqual(dims.width+4);
});
test('v1.84 sample practice lessons stay accessible without being promoted as extra class topics',async({page})=>{
 await page.goto('/#courses');await page.locator('body.v1590-ready').waitFor();
 const section=page.locator('#courses'),sample=section.locator('#v1840-sample-lessons');
 await sample.locator('summary').click();
 await expect(sample).toHaveAttribute('open','');
 await expect(sample.locator('.v1580-course-card:visible')).toHaveCount(3);
 await expect(sample.locator('.js-v1580-courses')).toHaveText('See all sample lessons');
 await sample.locator('.js-v1580-courses').click();
 await expect(sample.locator('.v1580-course-card:visible')).toHaveCount(9);
 await expect(sample.locator('.js-v1580-courses')).toHaveText('Show fewer sample lessons');
 await sample.locator('.v1580-course-card').nth(2).getByRole('button',{name:'Start a sample lesson'}).click();
 await expect(section.locator('#v1770-course-lesson')).toBeVisible();
 await expect(section.locator('#v1800-class-catalog .v1800-class-count')).toContainText('28 class topics');
});
