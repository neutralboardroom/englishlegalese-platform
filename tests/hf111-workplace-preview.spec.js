'use strict';
const {test,expect}=require('@playwright/test');
test('HF111 fictional workplace preview and optional comparison remain device-only',async({page})=>{
 const writes=[];page.on('request',r=>{if(['POST','PUT','PATCH','DELETE'].includes(r.method()))writes.push(r.url());});
 await page.goto('/learn/study-planner/');
 const p=page.locator('#hf111-workplace-preview');
 await expect(p).toBeVisible();
 await expect(p.locator('input[type=file],textarea,input[type=text]')).toHaveCount(0);
 const before=await page.evaluate(()=>({local:JSON.stringify(localStorage),session:JSON.stringify(sessionStorage)}));
 await p.locator('#hf111-scenario').selectOption('energy');
 await p.locator('#hf111-audience').selectOption('client');
 await p.locator('#hf111-level').selectOption('advanced');
 await p.locator('#hf111-build').click();
 await expect(p.locator('#hf111-output')).toContainText('delivery window');
 await expect(p.locator('#hf111-output')).toContainText('inspection is due');
 await expect(p.locator('details')).not.toHaveAttribute('open','');
 await p.locator('summary').click();
 await expect(p.locator('details')).toHaveAttribute('open','');
 await p.locator('#hf111-compare').click();
 await expect(p.locator('#hf111-comparison')).toContainText('Not compared');
 await p.locator('#hf111-baseline-0').selectOption('1');await p.locator('#hf111-repeat-0').selectOption('2');
 await p.locator('#hf111-compare').click();
 await expect(p.locator('#hf111-comparison')).toContainText('Higher self-rating');
 await p.locator('#hf111-scenario').selectOption('finance');
 await expect(p.locator('#hf111-output')).toBeHidden();
 await expect(p.locator('#hf111-comparison')).toBeHidden();
 await p.locator('#hf111-build').click();
 await expect(p.locator('#hf111-output')).toContainText('forecast revenue');
 await p.locator('#hf111-reset').click();
 await expect(p.locator('#hf111-output')).toBeHidden();
 const after=await page.evaluate(()=>({local:JSON.stringify(localStorage),session:JSON.stringify(sessionStorage)}));
 expect(after).toEqual(before);expect(writes).toEqual([]);
 const overflow=await page.evaluate(()=>document.documentElement.scrollWidth-document.documentElement.clientWidth);expect(overflow).toBeLessThanOrEqual(4);
});
