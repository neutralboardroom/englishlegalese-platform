'use strict';
const {test,expect}=require('@playwright/test');
for(const path of ['/learn/continuing-practice/','/learn/continuing-practice/advanced/']){
 test('HF50–HF52 professional coach ladder, accuracy challenge, timeboxed clinic, learner-only slides: '+path,async({page},info)=>{
  const writes=[],errors=[];
  page.on('request',r=>{if(['POST','PUT','PATCH','DELETE'].includes(r.method()))writes.push(r.url());});
  page.on('pageerror',e=>errors.push(e.message));
  await page.goto(path);
  await expect(page.locator('article.v1971-lesson')).toHaveCount(12);
  await expect(page.locator('.v2120-response-ladder')).toHaveCount(12);
  await expect(page.locator('.v2130-evidence-check')).toHaveCount(12);
  await expect(page.locator('.v2140-mini-clinic')).toHaveCount(12);
  const first=page.locator('article.v1971-lesson').first();
  await first.locator('details.v1990-speaking > summary').click();
  await first.locator('details.v2100-more-tools > summary').click();
  const ladder=first.locator('.v2120-response-ladder');await ladder.locator('summary').first().click();
  await expect(ladder.locator('.v2120-instructions')).toContainText('Supported model');
  const chooser=ladder.locator('.v2120-controls select');
  await chooser.selectOption('developing');await expect(ladder.locator('.v2120-instructions')).toContainText('source');
  await chooser.selectOption('confident');await expect(ladder.locator('.v2120-instructions')).toContainText('unsupported claim');
  const check=first.locator('.v2130-evidence-check');await check.locator('summary').first().click();
  await expect(check.locator('.v2130-choices button')).toHaveCount(3);
  await check.locator('.v2130-choices button').first().click();
  await expect(check.locator('.v2130-feedback')).toContainText('fact');
  await check.locator('.v2130-choices button').nth(1).click();
  await expect(check.locator('.v2130-feedback')).toContainText('Yes.');
  await check.locator('.v2130-repair summary').click();
  await expect(check.locator('.v2130-repair p').first()).toBeVisible();
  await check.getByRole('button',{name:'Try the three statements again'}).click();
  await expect(check.locator('.v2130-feedback')).toBeEmpty();
  const clinic=first.locator('.v2140-mini-clinic');await clinic.locator('summary').first().click();
  await expect(clinic.locator('.v2140-phases li')).toHaveCount(5);
  await clinic.getByRole('button',{name:'30-minute plan'}).click();
  await expect(clinic.locator('.v2140-phases li')).toHaveCount(6);
  await expect(clinic.locator('.v2140-plan')).toContainText('27–30 min');
  await clinic.getByRole('button',{name:'Open learner-only clinic preview'}).click();
  const dialog=page.locator('.v2140-learner-dialog');await expect(dialog).toBeVisible();
  await expect(dialog).toContainText('EnglishLegalese');
  await expect(dialog).not.toContainText('Facilitator');
  await expect(dialog.locator('textarea')).toHaveCount(0);
  await expect(dialog.locator('.v2140-slide-count')).toContainText('1 of 3');
  await dialog.getByRole('button',{name:'Next prompt'}).click();
  await expect(dialog.locator('.v2140-slide-count')).toContainText('2 of 3');
  await dialog.getByRole('button',{name:'Next prompt'}).click();
  await expect(dialog.locator('.v2140-slide-count')).toContainText('3 of 3');
  await dialog.getByRole('button',{name:'Close learner preview'}).click();
  await expect(page.locator('.v2140-learner-dialog')).toHaveCount(0);
  expect(writes).toEqual([]);expect(errors).toEqual([]);
  const dims=await page.evaluate(()=>[document.documentElement.scrollWidth,innerWidth]);
  expect(dims[0]).toBeLessThanOrEqual(dims[1]+2);
  await page.screenshot({path:info.outputPath('hf50-hf53-teaching-workflow.png'),fullPage:false});
 });
}
